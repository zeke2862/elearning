  /* 答錯橫幅（第一行粗體）的泰文對照；沒列在這裡的句子維持原樣 */
  var HEAD = {
    '📝 這題先記答錯，再練一次就會了！': '📝 ข้อนี้ตอบผิดไปก่อน ฝึกอีกครั้งก็จะทำได้แล้ว!',
    '📝 這題沒答對，看看解析吧；修羅要全對才達標，下次再挑戰！': '📝 ข้อนี้ตอบไม่ถูก ดูคำอธิบายกันก่อน โหมดอสูรต้องถูกทั้งหมดจึงจะผ่าน ไว้ท้าทายใหม่คราวหน้า!',
    '📝 這題沒答對，看看解析，下一題再加油！': '📝 ข้อนี้ตอบไม่ถูก ดูคำอธิบายแล้วสู้ต่อข้อต่อไป!',
    '⏰ 時間到囉，看看解析，下一題再加油！': '⏰ หมดเวลาแล้ว ดูคำอธิบายแล้วสู้ต่อข้อต่อไป!'
  };
  function headTh(box) {
    var b = box.querySelector && box.querySelector('b');
    if (b && HEAD[b.textContent]) b.textContent = HEAD[b.textContent];
  }

  /* 按鈕：在中文／泰文之間切換 */
  function attach(btn, box, zhHtml, thHtml, labelTh, labelZh) {
    var th = false;
    labelTh = labelTh || 'ไทย'; labelZh = labelZh || '中文';
    btn.type = 'button';
    btn.textContent = '🌐 ' + labelTh;
    btn.setAttribute('aria-label', 'แปลคำอธิบายเป็นภาษาไทย / 切換成泰文說明');
    btn.onclick = function (ev) {
      if (ev && ev.stopPropagation) ev.stopPropagation();
      th = !th;
      box.innerHTML = th ? thHtml : zhHtml;
      // 頁面上的「溫和橫幅」程式會在下一個瞬間改寫第一行，所以等它改完再換成泰文
      if (th) setTimeout(function () { if (th) headTh(box); }, 0);
      btn.textContent = th ? '🌐 ' + labelZh : '🌐 ' + labelTh;
      btn.setAttribute('aria-pressed', th ? 'true' : 'false');
    };
  }

