  function stepRaw(html) {
    var s = String(html == null ? '' : html).replace(/<br\s*\/?>/gi, ' ').replace(/<\/?(?:b|i|u|span|small|strong|em|sup|sub|div|p)\b[^>]*>/gi, '')
      .replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&');
    for (var i = 0; i < STEP.length; i++) s = s.replace(STEP[i][0], STEP[i][1]);
    s = s.replace(/大於等於|大於或等於/g, 'มากกว่าหรือเท่ากับ').replace(/小於等於|小於或等於/g, 'น้อยกว่าหรือเท่ากับ').replace(/(?<!不)大於/g, 'มากกว่า').replace(/(?<!不)小於/g, 'น้อยกว่า')
      .replace(/（不含等於）/g, ' (ไม่รวมเท่ากับ)').replace(/常數項/g, 'พจน์ค่าคงตัว').replace(/([xy]) 項/g, 'พจน์ $1');
    s = s.replace(/(不會改變|會改變)（因為乘\/除的是(正數|負數)）/g, function (m, a, b) { return (a === '會改變' ? 'เปลี่ยน' : 'ไม่เปลี่ยน') + ' (เพราะคูณ/หารด้วยจำนวน' + (b === '正數' ? 'บวก' : 'ลบ') + ')'; });
    for (var a = 0; a < ANSW.length; a++) s = s.split(ANSW[a][0]).join(ANSW[a][1]);
    s = s.replace(/第([一二三四])象限/g, function (m, c) { return 'จตุภาคที่ ' + QN[c]; });
    return tr(s).replace(/\.(?=[\u0E00-\u0E7F])/g, '. ');
  }
  /* 「點錯」提示用：還有句子沒收錄到泰文時，先給一句泰文提醒，再附上翻得出來的部分（數字、算式照原樣），不讓學生只看到一堆中文 */
  function step(html) {
    var hh = hintTh(html); if (hh) return hh;
    var s = stepRaw(html);
    if (/[一-鿿]/.test(s)) s = 'ขั้นตอนนี้ยังไม่ถูกต้อง ลองคิดอีกครั้งนะ (ข้อความอธิบายภาษาไทยของข้อนี้ยังไม่ครบ): ' + s;
    return s;
  }
  /* 教學「正面說明」用（小老師帶你做的每一步、老師教我的示範）：翻得完整才回泰文；
   * 還有中文沒翻到就回 null，呼叫的地方會改顯示中文原文（不顯示「半中半泰」的怪句子）。 */
  function say(html) {
    var h = hintTh(html);
    if (h) return h;
    var s = stepRaw(html);
    // 「不超過」(ไม่เกิน) 這種「中文＋泰文對照」的關鍵詞（題目用中文，所以保留）、以及人名記號，都不算沒翻完
    var chk = s.replace(NAME_MARK, '').replace(/「[\u4e00-\u9fff]+」 ?\([\u0E00-\u0E7F\/ ]+\)/g, '');
    return /[\u4e00-\u9fff]/.test(chk) ? null : s.replace(/[\u2060\u2061]/g, '');
  }

  /* ===== 說明語言（中文／泰文）：記在這台電腦的 localStorage「jb2-lang」，所有教學畫面共用 =====
   * JB2TH.lang()          → 'zh' 或 'th'
   * JB2TH.setLang('th')   → 切換並通知所有已開啟的教學畫面立刻改語言
   * JB2TH.onLang(fn)      → fn(lang) 在語言改變時被呼叫；回傳 false 代表不用再通知（畫面已關閉）
   * JB2TH.langBar()       → 回傳一個「中文｜ไทย」切換鈕（放進教學畫面的標題列） */
  var LKEY = 'jb2-lang', subs = [];
  function lang() { try { return localStorage.getItem(LKEY) === 'th' ? 'th' : 'zh'; } catch (e) { return 'zh'; } }
  function setLang(l) {
    l = l === 'th' ? 'th' : 'zh';
    try { localStorage.setItem(LKEY, l); } catch (e) {}
    var keep = [];
    subs.forEach(function (f) { var r; try { r = f(l); } catch (e) {} if (r !== false) keep.push(f); });
    subs = keep;
  }
  function onLang(f) { subs.push(f); }
  function langBar() {
    var w = document.createElement('span'), btn = {}, seen = false;
    w.className = 'jb2-langbar'; w.setAttribute('role', 'group'); w.setAttribute('aria-label', '說明語言 / ภาษาของคำอธิบาย');
    w.style.cssText = 'display:inline-flex;margin-left:10px;vertical-align:middle;border:1.5px solid #d2a24c;border-radius:999px;overflow:hidden;font-size:.8rem;font-weight:700;line-height:1;white-space:nowrap';
    ['zh', 'th'].forEach(function (k) {
      var x = document.createElement('button');
      x.type = 'button'; x.textContent = k === 'zh' ? '中文' : 'ไทย';
      x.style.cssText = 'border:0;margin:0;padding:6px 12px;cursor:pointer;font:inherit;color:inherit;background:transparent';
      x.onclick = function (ev) { if (ev && ev.stopPropagation) ev.stopPropagation(); if (lang() !== k) setLang(k); };
      w.appendChild(x); btn[k] = x;
    });
    function paint(l) {
      if (w.isConnected) seen = true; else if (seen) return false;
      ['zh', 'th'].forEach(function (k) {
        var on = k === l;
        btn[k].style.background = on ? '#d2a24c' : 'transparent';
        btn[k].style.color = on ? '#2a1d05' : 'inherit';
        btn[k].setAttribute('aria-pressed', on ? 'true' : 'false');
      });
    }
    paint(lang()); onLang(paint);
    return w;
  }

  window.JB2TH = { tr: tr, line: line, attach: attach, step: step, say: say, lang: lang, setLang: setLang, onLang: onLang, langBar: langBar, RULES: RULES };
